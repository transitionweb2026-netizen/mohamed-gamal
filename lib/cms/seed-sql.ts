import type { CmsSnapshot } from "./types";

/**
 * SQL that imports a snapshot into an empty (or partly filled) database.
 * Every statement is `on conflict do nothing`: existing rows are never
 * overwritten, so running it again is safe.
 */

type Row = Record<string, unknown>;

function literal(value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "null";
  if (Array.isArray(value) && value.every((v) => typeof v === "string")) {
    return value.length ? `array[${value.map((v) => literal(v)).join(", ")}]::text[]` : "'{}'::text[]";
  }
  if (typeof value === "object") return `${literal(JSON.stringify(value))}::jsonb`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Row[], conflict: string, omit: string[] = []): string {
  if (!rows.length) return "";
  const columns = Object.keys(rows[0]).filter((c) => !omit.includes(c));
  const values = rows.map((row) => `  (${columns.map((c) => literal(row[c])).join(", ")})`).join(",\n");
  const target = conflict ? `${conflict} ` : "";
  return `insert into public.${table} (${columns.join(", ")}) values\n${values}\non conflict ${target}do nothing;\n`;
}

export function seedSql(snapshot: CmsSnapshot): string {
  const parts = [
    "-- =============================================================================",
    "-- Dr. Mohamed Gamal — website content (generated by `npm run cms:seed-sql`).",
    "-- Imports the current website content. Never overwrites existing rows, so it",
    "-- is safe to run again. Do not edit by hand: change the content in the",
    "-- dashboard, or regenerate this file from content/ (a test checks it is current).",
    "-- =============================================================================",
    "",
    "begin;",
    "",
    // Media rows can collide on id, legacy path or bucket + path: skip any of them.
    insert("media", snapshot.media as unknown as Row[], "", ["created_at", "updated_at"]),
    snapshot.settings ? insert("site_settings", [snapshot.settings as unknown as Row], "(id)", ["updated_at"]) : "",
    insert("phone_numbers", snapshot.phones as unknown as Row[], "(id)"),
    insert("social_links", snapshot.socials as unknown as Row[], "(platform)"),
    insert("navigation_items", snapshot.navigation as unknown as Row[], "(key)"),
    insert("pages", snapshot.pages as unknown as Row[], "(key)", ["updated_at"]),
    insert("page_sections", snapshot.sections as unknown as Row[], "(page_key, key)", ["updated_at"]),
    insert("article_categories", snapshot.articleCategories as unknown as Row[], "(key)"),
    insert("services", snapshot.services as unknown as Row[], "(slug)"),
    insert("conditions", snapshot.conditions as unknown as Row[], "(slug)"),
    insert("process_steps", snapshot.processSteps as unknown as Row[], "(key)"),
    insert("stats", snapshot.stats as unknown as Row[], "(key)"),
    insert("videos", snapshot.videos as unknown as Row[], "(slug)"),
    insert("articles", snapshot.articles as unknown as Row[], "(slug)"),
    insert("testimonials", snapshot.testimonials as unknown as Row[], "(key)"),
    insert("faqs", snapshot.faqs as unknown as Row[], "(id)"),
    insert("credentials", snapshot.credentials as unknown as Row[], "(id)"),
    insert("ui_strings", snapshot.uiStrings as unknown as Row[], "(key)"),
    "commit;",
    "",
  ];
  return parts.filter((p) => p !== "").join("\n");
}
