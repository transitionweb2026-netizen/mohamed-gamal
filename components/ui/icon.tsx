export type IconName = keyof typeof icons;

export const ICON_NAMES = Object.keys(icons) as IconName[];

export function isIconName(value: unknown): value is IconName {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(icons, value);
}

/** Renders a registered icon; unknown names (e.g. from old content) fall back to Sparkles. */
export function Icon({ name, ...props }: { name: string } & LucideProps) {
  const Cmp = isIconName(name) ? icons[name] : Sparkles;
  return <Cmp aria-hidden strokeWidth={1.8} {...props} />;
}
